CREATE TABLE consentimento_termo (
  id_consentimento  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario        BIGINT      NOT NULL REFERENCES usuario (id_usuario) ON DELETE CASCADE ON UPDATE CASCADE,
  versao_termo      VARCHAR(20) NOT NULL,
  aceito_em         TIMESTAMP   NOT NULL DEFAULT now(),
  ip_origem         VARCHAR(45),
  CONSTRAINT uk_consentimento_usuario_versao UNIQUE (id_usuario, versao_termo)
);
